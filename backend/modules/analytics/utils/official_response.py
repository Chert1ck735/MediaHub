"""Распознавание официальных ответов организаций в тексте комментария."""
from __future__ import annotations

import re

from backend.modules.analytics.utils.text_normalize import normalized_lookup_text


def is_community_authored(author_external_id: str | None) -> bool:
    """True, если комментарий написан от имени сообщества/паблика, а не пользователя.

    В VK ``from_id`` отрицателен, когда автор — сообщество (паблик, группа): сам
    мониторируемый паблик отвечает жителям, либо комментирует другая
    организация (оператор связи и т.п.). Это надёжный детерминированный признак
    «не сообщение аудитории о проблеме», в отличие от текстовых эвристик
    ``looks_like_official_response`` (на digitalkrsk24 — 187/579 комментов, из
    которых текстовый детектор ловил лишь 64). ``author_external_id`` хранит
    именно ``from_id`` (см. ingestion). Работает для любого паблика без настройки.
    """

    aid = str(author_external_id or "").strip()
    return aid.startswith("-")


