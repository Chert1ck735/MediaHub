# VK хранит упоминание пользователя прямо в тексте комментария. Само по себе
# оно не является ответом: ``[id123|Иван],`` после отрисовки выглядит как
# нормальная реплика, но не несёт содержания.
_VK_MENTION_RE = re.compile(r"\[(?:id|club|public|event)\d+\|[^\]]+\]", re.IGNORECASE)


def is_meaningful_official_response(text: str | None) -> bool:
    """Есть ли в потенциальном ответе текст помимо VK-упоминаний и знаков.

    Это предохранитель от ложных официальных ответов, когда LLM принимает
    короткое ``[id...|Имя],`` за обращение администратора.
    """

    without_mentions = _VK_MENTION_RE.sub("", text or "")
    return bool(re.sub(r"[\W_]+", "", without_mentions, flags=re.UNICODE))


def looks_like_official_response(text: str, author_name: str | None = None) -> bool:
    """Похож ли комментарий на формальный ответ организации / модератора паблика.

    Используется при сборе аналитики, чтобы не считать «отписки» и
    паблик-менеджмент как проявление народной боли — они засоряют
    статистику и часто содержат те же ключевые слова, что и сами
    обращения.
    """

    low = normalized_lookup_text(text)
    author_low = normalized_lookup_text(author_name or "")
    if not low:
        return False

    if author_low and any(token in author_low for token in _OFFICIAL_AUTHOR_TOKENS):
        return True

    # Один уверенный модераторский токен — уже отсекаем.
    if any(token in low for token in _MODERATION_TOKENS):
        return True

    greeting = (
        low.startswith("добрый день")
        or " добрый день" in low[:80]
        or "здравствуйте" in low[:120]
    )
    formal_hits = sum(1 for token in _FORMAL_TOKENS if token in low)
    has_public_mention_greeting = bool(
        re.match(r"^\[[^\]]+\],\s*(добрый день|здравствуйте)", low)
    )
    if has_public_mention_greeting:  # «[id|Имя], добрый день» — ответ жителю, не боль
        return True
    return formal_hits >= 2 or (formal_hits >= 1 and greeting)
