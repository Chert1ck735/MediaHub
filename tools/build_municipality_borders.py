"""Генерирует слой границ МО для Yandex Maps из topology-preserving GeoJSON.

Использование:
  npx --yes mapshaper -i GEOJSON_MO_border.geojson encoding=cp1251 \\
    -clean overlap-rule=min-area rewind -simplify 5% method=dp keep-shapes \\
    -o format=geojson %TEMP%/mediahub-mo-topology.geojson
  python tools/build_municipality_borders.py %TEMP%/mediahub-mo-topology.geojson

Упрощение исходного файла выполняется Mapshaper в одном слое, чтобы общие
границы муниципалитетов оставались общими и не давали наложений на карте.
"""
from __future__ import annotations

import json
import sys
from pathlib import Path
import re


ROOT = Path(__file__).resolve().parents[1]
OUTPUT = ROOT / "frontend" / "src" / "app" / "municipalityBorders.ts"


def normalize_key(name: str) -> str:
    stopwords = {"городской", "муниципальный", "округ", "район", "зато", "город", "г", "п", "поселок"}
    tokens = re.sub(r"[«»'.,]", "", name.lower().replace("ё", "е")).split()
    return " ".join(token for token in tokens if token not in stopwords)


def swap_position(position: list[float]) -> list[float]:
    """GeoJSON [lon, lat] -> координаты Yandex Maps [lat, lon]."""
    return [round(float(position[1]), 6), round(float(position[0]), 6)]


def as_polygons(geometry: dict) -> list[list[list[list[float]]]]:
    coordinates = geometry["coordinates"]
    if geometry["type"] == "Polygon":
        coordinates = [coordinates]
    if geometry["type"] != "MultiPolygon" and geometry["type"] != "Polygon":
        raise ValueError(f"Unsupported geometry type: {geometry['type']}")
    return [
        [[swap_position(point) for point in ring] for ring in polygon]
        for polygon in coordinates
    ]


def main() -> None:
    source = Path(sys.argv[1]) if len(sys.argv) == 2 else None
    if source is None or not source.is_file():
        raise SystemExit("Usage: python tools/build_municipality_borders.py <simplified.geojson>")

    payload = json.loads(source.read_text(encoding="utf-8"))
    borders = []
    for feature in payload["features"]:
        name = str(feature.get("properties", {}).get("NAME") or "").strip()
        if not name:
            raise ValueError("Municipality feature has no NAME")
        borders.append({
            "name": name,
            "key": normalize_key(name),
            "polygons": as_polygons(feature["geometry"]),
        })

    header = """// AUTOGENERATED from GEOJSON_MO_border.geojson.\n// Geometry is topology-preserving simplified in one layer; coordinates are [lat, lon] for Yandex Maps.\n// Do not edit manually; see tools/build_municipality_borders.py.\nexport type MunicipalityBorder = { name: string; key: string; polygons: number[][][][] };\nexport const MUNICIPALITY_BORDERS: MunicipalityBorder[] = """
    OUTPUT.write_text(header + json.dumps(borders, ensure_ascii=False, separators=(",", ":")) + ";\n", encoding="utf-8")
    print(f"Wrote {len(borders)} municipalities to {OUTPUT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
